import assert from 'node:assert/strict';
import { dopisz,porownaj,kluczKarty,WERSJA,PROBKA } from './lib/eksperyment-historii-kart.mjs';

const t=1_800_000_000;
const card={id:'12345',name:'Przykladowa karta',price:5000};
const id=kluczKarty(87,card);
assert.equal(id,'87|12345|Przykladowa karta');
assert.equal(kluczKarty(87,{name:'bez ID',price:5000}),null);
let stan=null;
for(let i=0;i<60;i++){
  const at=t+i*600;
  const bands={ps:{87:[{...card,price:i===35?1000:5000}]},pc:{87:[{...card,price:6000}]}};
  const x=dopisz(stan,bands,at);
  stan=x.stan;
  assert.equal(stan.ps[id].punkty.length,i+1);
  assert.equal(stan.pc[id].punkty.length,i+1);
  const repeated=dopisz(stan,bands,at+60);
  assert.equal(repeated.statystyki.dopisano,0);
}
const p=porownaj(stan,'ps',87,card,t+60*600);
const pc=porownaj(stan,'pc',87,card,t+60*600);
assert.ok(p.gotowe,p.powod);
assert.ok(pc.gotowe,pc.powod);
assert.equal(p.mediana12,5000,'mediana nie reaguje na pojedynczy zly tick');
assert.ok(p.ema12<5000&&p.ema12>4000);
assert.equal(pc.mediana12,6000,'PC ma osobna historie');
assert.equal(pc.ema12,6000);
assert.equal(p.liczba,60);
const withFuture=dopisz(stan,{ps:{87:[{...card,price:9500}]},pc:{}},t+60*600);
const noLookahead=porownaj(withFuture.stan,'ps',87,card,t+60*600);
assert.equal(noLookahead.mediana12,p.mediana12,'oceniana probka NIE wchodzi do poziomu bazowego');
assert.equal(noLookahead.ema12,p.ema12);
const none=porownaj(stan,'ps',87,{...card,id:'xyz'},t+60*600);
assert.equal(none.gotowe,false);
const bad=dopisz(stan,{ps:{87:[{...card,price:9750},{name:'Brak id',price:5000}]},pc:{}},t+61*600);
assert.equal(bad.statystyki.odrzucono,2);
const afterGap=porownaj(stan,'ps',87,card,t+90*600);
assert.equal(afterGap.gotowe,false);
const sparse={wersja:WERSJA,ps:{[id]:{punkty:Array.from({length:60},(_,i)=>[t+i*1800,5000])}},pc:{}};
assert.equal(porownaj(sparse,'ps',87,card,t+180*600).gotowe,false,'luka i przestarzaly punkt nie daje wyceny');
const reset=dopisz(stan,{ps:{},pc:{}},t+5*86400);
assert.equal(Object.keys(reset.stan.ps).length,0,'retencja usuwa stare rekordy bez zastepowania ich zerami');
const onlyMissing={ps:{87:[]},pc:{87:[]}};
assert.equal(dopisz(null,onlyMissing,t).statystyki.dopisano,0);
console.log('OK: 10-minutowe probkowanie, rozdzial rynkow i ID, retencja, brak lookahead');
console.log('OK: mediana/EMA/hybryda na tych samych probkach; brak wyceny po przerwie');
console.log('OK: jednostkowy ekstremalny tick nie zaburza mediany');
